export function localizeLearnSection<T extends LearnSection>(locale: Locale, section: T): T {
  const translated = locale === 'zh-TW' ? learnZhTW[section.id] : undefined;
  return translated ? { ...section, ...translated } : section;
}

// Keep the screen-section shape visible to typechecking when translations include a question.
export const localizeLearnTabSection = (locale: Locale, section: LearnTabSection): LearnTabSection =>
  localizeLearnSection(locale, section);
